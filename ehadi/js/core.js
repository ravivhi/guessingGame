  /* ---------------------------------------------------------------- speech
     Text is turned into words a voice can read (math symbols, blanks, fractions, units), split into short
     sentences and spoken one at a time. Short pieces avoid browsers cutting long utterances off, and a
     piece that fails with one voice is retried once with the next best voice. */
  var SPOKEN = {
    en: { plus: 'plus', minus: 'minus', times: 'times', div: 'divided by', eq: 'equals', blank: 'what number', over: 'over', and: 'and', to: 'to', lt: 'is less than ', gt: 'is greater than ', about: 'is about', pct: 'percent', deg: 'degrees', sq: 'squared', cube: 'cubed', pi: 'pi', ratio: ' to ', shekel: 'shekels', rem: 'remainder', mixed: '$1 and $2/$3' },
    he: { plus: 'ועוד', minus: 'פחות', times: 'כפול', div: 'לחלק ל', eq: 'שווה', blank: 'כמה', over: 'חלקי', and: 'ועוד', to: 'עד', lt: 'קטן מ', gt: 'גדול מ', about: 'בערך', pct: 'אחוז', deg: 'מעלות', sq: 'בריבוע', cube: 'בחזקת שלוש', pi: 'פאי', ratio: ' ל', shekel: 'שקלים', rem: 'שארית', mixed: '$1 ו$2/$3' }
  };
  var SPOKEN_UNITS = {
    en: [[/cm²/g, 'square centimeters'], [/cm³/g, 'cubic centimeters'], [/\bm²/g, 'square meters'], [/km\/h/g, 'kilometers per hour'], [/\bkm\b/g, 'kilometers'], [/\bcm\b/g, 'centimeters'], [/\bmm\b/g, 'millimeters'], [/\bkg\b/g, 'kilograms'], [/\bml\b/g, 'milliliters']],
    he: [[/סמ["״]ר/g, 'סנטימטר רבוע'], [/סמ["״]ק/g, 'סנטימטר מעוקב'], [/קמ["״]ש/g, 'קילומטר לשעה'], [/ס["״]מ/g, 'סנטימטר'], [/מ["״]מ/g, 'מילימטר'], [/ק["״]מ/g, 'קילומטר'], [/ק["״]ג/g, 'קילוגרם'], [/מ["״]ל/g, 'מיליליטר'], [/מ["״]ר/g, 'מטר רבוע'], [/שנ[׳']/g, 'שניות'], [/דק[׳']/g, 'דקות'], [/שע[׳']/g, 'שעות'], [/אג[׳']/g, 'אגורות'], [/(^|[^א-ת])מ[׳']/g, '$1מטר']]
  };
  var BLANK = '\u0007';
  function speakable(s, lang) {
    var he = /^(he|iw)/i.test(lang), W = SPOKEN[he ? 'he' : 'en'];
    s = String(s).replace(/<\/?[a-z][^>]*>/gi, ' ').replace(/[\u2066-\u2069\u200e\u200f\u202a-\u202e\ufe0f]/g, '').replace(/[✅❌✔✓✗➜▶]|💡|🔊|🔎/g, '');
    SPOKEN_UNITS[he ? 'he' : 'en'].forEach(function (r) { s = s.replace(r[0], r[1]); });
    if (he) s = s.replace(/־(?=\d)/g, '').replace(/־/g, ' ');
    s = s.replace(/([\d?])\s+R(?=\s|$|[.,])/g, '$1 ' + W.rem)
      .replace(new RegExp('(\\d\\s+' + W.rem + '\\s*)\\?', 'g'), '$1' + BLANK).replace(new RegExp('\\?(\\s*' + W.rem + '\\s+\\d)', 'g'), BLANK + '$1');
    s = s.replace(/\?\s*\/\s*\?/g, BLANK).replace(/_+|□/g, BLANK)
      .replace(/\?\s*\/\s*(\d)/g, BLANK + ' ' + W.over + ' $1').replace(/(\d)\s*\/\s*\?/g, '$1 ' + W.over + ' ' + BLANK)
      .replace(/([=+\-−×÷<>(,]\s*)\?/g, '$1' + BLANK).replace(/\?(\s*[=+\-−×÷<>)])/g, BLANK + '$1')
      .replace(/(\d)\s+(\d+)\s*\/\s*(\d+)/g, W.mixed)
      .replace(/(\d+)\s*\/\s*(\d+)/g, '$1 ' + W.over + ' $2')
      .replace(/(\d)\s*[–—]\s*(\d)/g, '$1 ' + W.to + ' $2')
      .replace(/(\d)\s+:\s+(\d)/g, '$1' + W.ratio + '$2')
      .replace(/²/g, ' ' + W.sq).replace(/³/g, ' ' + W.cube).replace(/°/g, ' ' + W.deg).replace(/%/g, ' ' + W.pct).replace(/π/g, ' ' + W.pi + ' ')
      .replace(/×/g, ' ' + W.times + ' ').replace(/\s*÷\s*/g, ' ' + W.div + (he ? '' : ' ')).replace(/\+/g, ' ' + W.plus + ' ').replace(/−/g, ' ' + W.minus + ' ')
      .replace(new RegExp('([\\d)' + BLANK + ']\\s*)-(\\s*[\\d(' + BLANK + '])', 'g'), '$1 ' + W.minus + ' $2')
      .replace(/≈/g, ' ' + W.about + ' ').replace(/=/g, ' ' + W.eq + ' ')
      .replace(/\s*<\s*/g, ' ' + W.lt).replace(/\s*>\s*/g, ' ' + W.gt)
      .replace(/₪/g, ' ' + W.shekel).replace(/[()]/g, ', ').replace(/[→•…]/g, ', ')
      .replace(new RegExp(BLANK, 'g'), ' ' + W.blank + ' ')
      .replace(/\s+([,.!?:;])/g, '$1').replace(/,\s*([.!?:;])/g, '$1').replace(/([,:;])(\s*,)+/g, '$1').replace(/([.!?])\s*,/g, '$1').replace(/^[\s,]+/, '').replace(/\s{2,}/g, ' ').trim();
    if (he) s = s.replace(/(לחלק ל|קטן מ|גדול מ)\s+/g, '$1');
    return s;
  }
  function speechChunks(s) {
    var MAX = 160, out = [], merged = [];
    s.replace(/([.!?;])\s+/g, '$1\n').split(/\n+/).forEach(function (p) {
      p = p.trim();
      while (p.length > MAX) {
        var cut = p.lastIndexOf(', ', MAX);
        if (cut < 40) cut = p.lastIndexOf(' ', MAX);
        if (cut < 20) cut = MAX;
        out.push(p.slice(0, cut + 1).trim()); p = p.slice(cut + 1).trim();
      }
      if (p) out.push(p);
    });
    out.forEach(function (p) { var i = merged.length - 1; if (i >= 0 && merged[i].length + p.length + 1 <= MAX) merged[i] += ' ' + p; else merged.push(p); });
    return merged;
  }
  var sp = { queue: [], current: null, startTimer: null, watchdog: null, gen: 0, voices: {}, bad: {}, warned: false };
  function voiceFor(lang) {
    if (sp.voices[lang] !== undefined && !(sp.voices[lang] && sp.bad[sp.voices[lang].name])) return sp.voices[lang];
    var all = G.speechSynthesis.getVoices() || [], pre = lang.slice(0, 2).toLowerCase(), alts = pre === 'he' || pre === 'iw' ? ['he', 'iw'] : [pre];
    var mine = all.filter(function (v) {
      var l = String(v.lang || '').toLowerCase().replace('_', '-');
      return !sp.bad[v.name] && alts.some(function (a) { return l === a || l.indexOf(a + '-') === 0; });
    });
    var score = function (v) { return (/natural/i.test(v.name) ? 4 : 0) + (/online|neural|google/i.test(v.name) ? 2 : 0) + (String(v.lang).toLowerCase().replace('_', '-') === lang.toLowerCase() ? 1 : 0); };
    mine.sort(function (a, b) { return score(b) - score(a); });
    if (!all.length) return null;
    sp.voices[lang] = mine[0] || null;
    return sp.voices[lang];
  }
  function pump() {
    if (sp.current || !sp.queue.length) return;
    var item = sp.queue.shift(), gen = sp.gen, v = voiceFor(item.lang), ut;
    if (!v && !sp.warned && (G.speechSynthesis.getVoices() || []).length) { sp.warned = true; MA.toast(MA.t('speech_no_voice'), { icon: '🔇', ms: 6000 }); }
    try {
      ut = new G.SpeechSynthesisUtterance(item.text);
      ut.lang = item.lang; if (v) ut.voice = v; ut.rate = .9;
    } catch (e) { return; }
    sp.current = ut;
    var done = function (ev) {
      if (sp.current !== ut) return;
      clearTimeout(sp.watchdog); sp.current = null;
      if (ev && ev.type === 'error' && v && !/interrupted|canceled|not-allowed/.test(ev.error || '') && !item.retried) { sp.bad[v.name] = 1; item.retried = true; sp.queue.unshift(item); }
      if (gen === sp.gen) setTimeout(pump, 40);
    };
    ut.onend = done; ut.onerror = done;
    sp.watchdog = setTimeout(done, 3000 + item.text.length * 150);   /* some browsers never fire onend */
    try { G.speechSynthesis.resume(); G.speechSynthesis.speak(ut); } catch (e) { done(); }
  }
  function stopSpeech() {
    sp.gen++; sp.queue = []; sp.current = null;
    clearTimeout(sp.watchdog); clearTimeout(sp.startTimer); sp.startTimer = null;
    try { G.speechSynthesis.cancel(); } catch (e) { /* ignore */ }
  }
  MA.speech = {
    supported: hasDOM && 'speechSynthesis' in G && typeof G.SpeechSynthesisUtterance === 'function',
    text: speakable,
    chunks: speechChunks,
    /* o.queue: add after what is already being read instead of interrupting it */
    say: function (text, o) {
      if (!MA.speech.supported || !text) return;
      o = o || {};
      var lang = MA.i18n.locale(), parts = speechChunks(speakable(text, lang));
      if (!parts.length) return;
      if (!o.queue) stopSpeech();
      parts.forEach(function (p) { sp.queue.push({ text: p, lang: lang }); });
      if (sp.startTimer || sp.current) return;
      /* wait a moment after cancel() (Chrome drops speech started right away) and for the voice list on first use */
      var gen = sp.gen, delay = (G.speechSynthesis.getVoices() || []).length ? (o.queue ? 0 : 120) : 700;
      sp.startTimer = setTimeout(function () { sp.startTimer = null; if (gen === sp.gen) pump(); }, delay);
    },
    stop: function () { if (MA.speech.supported) stopSpeech(); }
  };
  if (MA.speech.supported) {
    try {
      G.speechSynthesis.getVoices();
      G.speechSynthesis.addEventListener('voiceschanged', function () { sp.voices = {}; });
    } catch (e) { /* ignore */ }
  }
